"""Write supabase/seed.sql from data/*.json, the offline copy of the Supabase catalog.

Run it after editing data/, then run the output in the Supabase SQL editor (or with the MCP
execute_sql tool). It is idempotent: records are upserted, then rows no longer in data/ are deleted.
Usage:  .venv\\Scripts\\python scripts\\export_supabase_seed.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
OUT = ROOT / "supabase" / "seed.sql"
COLLECTIONS = ("destinations", "devices", "personas", "dossiers")
MAX_STATEMENT_BYTES = 24_000
TAG = "$bp$"


def jsonb(obj) -> str:
    text = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    if TAG in text:
        raise ValueError(f"{TAG} appears in the data; pick another dollar-quote tag")
    return f"{TAG}{text}{TAG}::jsonb"


def text(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def batches(values: list[str]):
    batch, size = [], 0
    for v in values:
        n = len(v.encode("utf-8"))
        if batch and size + n > MAX_STATEMENT_BYTES:
            yield batch
            batch, size = [], 0
        batch.append(v)
        size += n
    if batch:
        yield batch


def main() -> None:
    docs = {name: json.loads((DATA_DIR / f"{name}.json").read_text(encoding="utf-8")) for name in COLLECTIONS}
    persona_ids = {p["name"]: p["id"] for p in docs["personas"]["personas"]}
    upserts, deletes = [], []

    settings = [f"({text(name)}, {text(key)}, {jsonb(value)})"
                for name in COLLECTIONS for key, value in docs[name].items() if key != name]
    upserts.append("insert into public.catalog_settings (collection, key, value) values\n  "
                   + ",\n  ".join(settings)
                   + "\non conflict (collection, key) do update set value = excluded.value;")

    for name in ("destinations", "devices", "personas"):
        rows = [f"({i}, {jsonb(r)})" for i, r in enumerate(docs[name][name])]
        for batch in batches(rows):
            upserts.append(f"insert into public.{name} (id, sort_order, name, data)\n"
                           "select v.data->>'id', v.sort_order, v.data->>'name', v.data\n"
                           "from (values\n  " + ",\n  ".join(batch) + "\n) as v (sort_order, data)\n"
                           "on conflict (id) do update set sort_order = excluded.sort_order, "
                           "name = excluded.name, data = excluded.data;")

    rows = [f"({i}, {text(persona_ids[d['patient']])}, {jsonb(d)})" for i, d in enumerate(docs["dossiers"]["dossiers"])]
    for batch in batches(rows):
        upserts.append("insert into public.dossiers (id, sort_order, persona_id, destination_id, device_id, data)\n"
                       "select v.data->>'id', v.sort_order, v.persona_id, v.data->>'destId', v.data->>'deviceId', v.data\n"
                       "from (values\n  " + ",\n  ".join(batch) + "\n) as v (sort_order, persona_id, data)\n"
                       "on conflict (id) do update set sort_order = excluded.sort_order, persona_id = excluded.persona_id, "
                       "destination_id = excluded.destination_id, device_id = excluded.device_id, data = excluded.data;")

    for name in ("dossiers", "personas", "devices", "destinations"):  # children first, for the foreign keys
        ids = ", ".join(text(r["id"]) for r in docs[name][name])
        deletes.append(f"delete from public.{name} where id <> all (array[{ids}]);")
    keys = ", ".join(f"({text(n)}, {text(k)})" for n in COLLECTIONS for k in docs[n] if k != n)
    deletes.append(f"delete from public.catalog_settings where (collection, key) not in (values {keys});")

    parts = ["-- Generated by scripts/export_supabase_seed.py from data/*.json. Do not edit by hand.", "begin;"]
    for i, stmt in enumerate(upserts, 1):
        parts.append(f"-- upsert {i}/{len(upserts)}\n{stmt}")
    parts.append("-- remove rows that are no longer in data/\n" + "\n".join(deletes))
    parts.append("commit;")
    OUT.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(upserts)} upsert statements, "
          f"{sum(len(docs[n][n]) for n in COLLECTIONS)} records, {len(settings)} settings.")


if __name__ == "__main__":
    main()
